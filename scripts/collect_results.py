#!/usr/bin/env python3
"""Regenerate results/comparison.md from the per-core JSON summaries.

Exit gate 5 of every phase appends a row here, so the final cross-core
comparison builds up incrementally instead of being reconstructed at the end
from numbers measured months apart under different tool versions.
"""
from __future__ import annotations

import json
from pathlib import Path

ORDER = ["core_rv32i"]
LABEL = {
    "core_rv32i": "RV32I single-cycle",
}

HEADER = """# Core Comparison

Regenerated by `make results`. Every core is measured on identical stimulus
with the same pinned toolchain, so the rows are directly comparable.

"""

FOOTER = """
**IPC alone is misleading.** A single-cycle datapath retires one instruction per
clock, but one clock period must then contain fetch, decode, execute, memory and
writeback - so it buys its IPC with a slow clock. Real throughput is
`IPC x Fmax`, which is why both are recorded and why the MIPS column exists.

**MIPS is only comparable within one ISA.** It counts instructions, not work.
An RV32I core scores far higher MIPS than an RV32IM core on the same C source
purely because it executes far more instructions to compute the same answer -
libgcc replaces one `div` with dozens of shift-and-subtract steps. Compare wall
clock on identical source, never MIPS across different instruction sets.

**Cycle-count CSRs cannot be compared against an ISS.** Spike is instruction
accurate, not cycle accurate, so any test reading mcycle/cycle will legitimately
disagree with RTL once IPC differs from 1. This matters more from Phase 2 on.
"""


def main() -> int:
    raw = Path("results/raw")
    rows = []
    for core in ORDER:
        synth_f = raw / f"{core}_synth.json"
        if not synth_f.exists():
            continue
        s = json.loads(synth_f.read_text())

        ipc_f = raw / f"{core}_ipc.json"
        ipc = json.loads(ipc_f.read_text())["ipc"] if ipc_f.exists() else None

        ipc_s = f"{ipc:.3f}" if ipc is not None else "-"
        mips = f"{ipc * s['fmax_mhz']:.1f}" if ipc is not None else "-"
        area = f"{s['lut']} / {s['ff']} / {s['bram']} / {s['dsp']}"
        rows.append(f"| {LABEL[core]} | {ipc_s} | {s['fmax_mhz']:.1f} | {area} | {mips} |")

    out = [
        HEADER,
        "| Core | IPC | Fmax (MHz) | LUT / FF / BRAM / DSP | MIPS |",
        "|---|---|---|---|---|",
        *rows,
        FOOTER,
    ]
    Path("results").mkdir(exist_ok=True)
    Path("results/comparison.md").write_text("\n".join(out))
    print(f"Wrote results/comparison.md with {len(rows)} row(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
